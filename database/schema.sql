-- SME Digital Collective — MySQL / MariaDB schema
-- Import this file into MySQL/MariaDB to create the application database and tables.
CREATE DATABASE IF NOT EXISTS sme_agency CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sme_agency;

CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(200) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL, role VARCHAR(30) NOT NULL DEFAULT 'admin',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS admin_remember_tokens (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, admin_id INT NOT NULL,
  selector CHAR(24) NOT NULL UNIQUE, token_hash CHAR(64) NOT NULL,
  expires_at DATETIME NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used_at TIMESTAMP NULL DEFAULT NULL, INDEX (admin_id), INDEX (expires_at),
  FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS services (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, slug VARCHAR(120) NOT NULL UNIQUE,
  short_description VARCHAR(300) NOT NULL, full_description TEXT NOT NULL,
  starting_price INT NOT NULL DEFAULT 0, billing_unit VARCHAR(30) NOT NULL DEFAULT 'one-off',
  features JSON NULL, image VARCHAR(255) NOT NULL DEFAULT '',
  is_active TINYINT(1) NOT NULL DEFAULT 1, is_featured TINYINT(1) NOT NULL DEFAULT 0, display_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS clients (
  id INT AUTO_INCREMENT PRIMARY KEY, business_name VARCHAR(160) NOT NULL, contact_name VARCHAR(120) NOT NULL,
  email VARCHAR(200) NOT NULL UNIQUE, phone VARCHAR(40) NOT NULL, address VARCHAR(300) NOT NULL DEFAULT '',
  status VARCHAR(30) NOT NULL DEFAULT 'Active', notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inquiries (
  id INT AUTO_INCREMENT PRIMARY KEY, inquiry_number VARCHAR(40) NOT NULL UNIQUE, full_name VARCHAR(120) NOT NULL,
  business_name VARCHAR(160) NOT NULL, email VARCHAR(200) NOT NULL, phone VARCHAR(40) NOT NULL,
  preferred_contact_method VARCHAR(30) NOT NULL DEFAULT 'Email', message TEXT NULL, budget_range VARCHAR(80) NOT NULL DEFAULT '',
  status ENUM('New','Contacted','In Discussion','Quoted','Converted','Closed','Rejected') NOT NULL DEFAULT 'New',
  source VARCHAR(20) NOT NULL DEFAULT 'quote', client_id INT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX (status), INDEX (created_at),
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inquiry_services (
  id INT AUTO_INCREMENT PRIMARY KEY, inquiry_id INT NOT NULL, service_id INT NOT NULL, UNIQUE (inquiry_id, service_id),
  FOREIGN KEY (inquiry_id) REFERENCES inquiries(id) ON DELETE CASCADE, FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inquiry_details (
  id INT AUTO_INCREMENT PRIMARY KEY, inquiry_id INT NOT NULL, detail_key VARCHAR(60) NOT NULL, detail_value VARCHAR(600) NOT NULL,
  FOREIGN KEY (inquiry_id) REFERENCES inquiries(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inquiry_notes (
  id INT AUTO_INCREMENT PRIMARY KEY, inquiry_id INT NOT NULL, admin_id INT NULL, note TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (inquiry_id) REFERENCES inquiries(id) ON DELETE CASCADE, FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inquiry_activity (
  id INT AUTO_INCREMENT PRIMARY KEY, inquiry_id INT NOT NULL, action VARCHAR(200) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (inquiry_id) REFERENCES inquiries(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS projects (
  id INT AUTO_INCREMENT PRIMARY KEY, client_id INT NOT NULL, service_id INT NULL, name VARCHAR(200) NOT NULL, description TEXT NULL,
  status ENUM('Pending','Active','Awaiting Client','Completed','Cancelled') NOT NULL DEFAULT 'Pending',
  agreed_price INT NOT NULL DEFAULT 0, amount_paid INT NOT NULL DEFAULT 0,
  start_date DATE NULL, expected_completion_date DATE NULL, completed_date DATE NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE, FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
-- Outstanding balance = agreed_price - amount_paid
CREATE OR REPLACE VIEW project_balances AS SELECT id, name, agreed_price, amount_paid, (agreed_price - amount_paid) AS outstanding_balance FROM projects;
CREATE TABLE IF NOT EXISTS team_members (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, role VARCHAR(120) NOT NULL, bio VARCHAR(600) NOT NULL DEFAULT '',
  photo VARCHAR(255) NOT NULL DEFAULT '', email VARCHAR(200) NOT NULL DEFAULT '', linkedin_url VARCHAR(300) NOT NULL DEFAULT '',
  display_order INT NOT NULL DEFAULT 0, is_active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (
  id INT AUTO_INCREMENT PRIMARY KEY, setting_key VARCHAR(60) NOT NULL UNIQUE, setting_value VARCHAR(600) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_limits (
  id INT AUTO_INCREMENT PRIMARY KEY, ip VARCHAR(45) NOT NULL, bucket VARCHAR(30) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX (ip, bucket, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
